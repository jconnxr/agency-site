// Converts the source photos into responsive WebP files in public/images/
// and writes src/lib/images.ts, the manifest the custom next/image loader reads.
//
//   node scripts/optimize-images.mjs [source-folder]
//
// Source folder defaults to ~/Desktop/site-images. Widths are never upscaled:
// a width larger than the source is dropped and the source width is used instead.
import { mkdir, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import path from "node:path";
import sharp from "sharp";

const SRC = process.argv[2] ?? path.join(homedir(), "Desktop/site-images");
const OUT = path.resolve("public/images");
const MANIFEST = path.resolve("src/lib/images.ts");

const WIDE = [640, 1280, 2000]; // capped at the source width (1024 for the current photos)
const CARD = [480, 960];

// name -> which width set it gets
const images = {
  "designer-okc-skyline": WIDE,
  "drone-operator": WIDE,
  "aerial-roof": WIDE,
  "barbershop-meeting": CARD,
  "contractor-truck": CARD,
  "local-search-plaza": CARD,
  "auto-shop-counter": CARD,
  "chef-filming": CARD,
};

await mkdir(OUT, { recursive: true });
const manifest = {};

for (const [name, wanted] of Object.entries(images)) {
  const input = path.join(SRC, `${name}.png`);
  const { width, height } = await sharp(input).metadata();
  const widths = [...new Set(wanted.map((w) => Math.min(w, width)))].sort((a, b) => a - b);

  for (const w of widths) {
    const file = path.join(OUT, `${name}-${w}.webp`);
    const info = await sharp(input)
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: 74, effort: 6, smartSubsample: true })
      .toFile(file);
    console.log(`${name}-${w}.webp  ${info.width}x${info.height}  ${(info.size / 1024).toFixed(0)} KB`);
  }
  manifest[`/images/${name}.webp`] = { width, height, widths };
}

await writeFile(
  MANIFEST,
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.
// Maps each photo's src to its source size and the widths exported to public/images/.
export const imageManifest: Record<string, { width: number; height: number; widths: number[] }> = ${JSON.stringify(manifest, null, 2)};
`
);
console.log(`\nWrote ${path.relative(process.cwd(), MANIFEST)}`);
